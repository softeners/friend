@lru_cache(maxsize=None)
def _dims(slug):
    """Родные пропорции кадра — из готового -1200.jpg, а не из сырого исходника.

    Кадры лонгрида не обрезаются по рамке (см. .longread .ph в pages.css),
    высота у них следует за шириной. Без width/height на <img> браузер до
    загрузки файла не знает будущую высоту, .ph схлопывается в 0 и вся
    разметка ниже прыгает при подгрузке фото — а native loading="lazy"
    у Chrome теряет счёт, где на самом деле находится следующий кадр,
    и часть снимков в конце статьи так и не подгружается при обычной
    прокрутке. width/height решают оба: браузер резервирует высоту заранее.
    """
    path = os.path.join(_PHOTO_DIR, f'{slug}-1200.jpg')
    with Image.open(path) as im:
        return im.size


def _pic(slug, alt, sizes):
    w, h = _dims(slug)
    return (f'<picture data-slug="{slug}">\n'
            f'          <source type="image/webp" srcset="{PHOTO}/{slug}-600.webp 600w, '
            f'{PHOTO}/{slug}-1200.webp 1200w" sizes="{sizes}">\n'
            f'          <img src="{PHOTO}/{slug}-1200.jpg" alt="{alt}" width="{w}" height="{h}" '
            f'loading="lazy" decoding="async">\n'
            f'        </picture>')


def fig(slug, alt, ratio='4x3', wide=False):
    """Один кадр в колонку текста. wide — во всю ширину контейнера."""
    sizes = '100vw' if wide else '(max-width: 900px) 92vw, 66ch'
    return f'''<figure class="{'is-wide' if wide else ''}">
      <div class="ph ph--{ratio}">
        {_pic(slug, alt, sizes)}
      </div>
    </figure>'''


def row(items, ratio='3x4'):
    """Несколько кадров в ряд: триптих или пара."""
    cells = '\n'.join(f'''<div class="ph ph--{ratio}">
        {_pic(slug, alt, '(max-width: 700px) 92vw, 30vw')}
      </div>''' for slug, alt in items)
    return f'''<figure class="is-wide longread__row" style="--cols:{len(items)}">
      {cells}
    </figure>'''


def p(*lines):
    """Абзац за абзацем — по строке, как в авторском тексте."""
    return '\n\n      '.join(f'<p>{l}</p>' for l in lines)


